    #[test]
    fn managed_workflow_updates_only_when_the_existing_copy_is_unmodified() {
        let temp = tempfile::tempdir().unwrap();
        let settings = WorkflowSettings {
            default_branch: "main".into(),
            manifest_path: PathBuf::from("gleam.toml"),
            compiler: "1.18.1".into(),
            environment: "release".into(),
            registry_credential_env: "HEXPM_API_KEY".into(),
            release_branch_prefix: "release-glz/".into(),
            action_sha: "abcdef0123456789abcdef0123456789abcdef01".into(),
        };
        let created = sync(temp.path(), &settings, WorkflowMode::Update).unwrap();
        assert!(created.changed);
        let unchanged = sync(temp.path(), &settings, WorkflowMode::Check).unwrap();
        assert!(!unchanged.changed);

        let path = temp.path().join(WORKFLOW_PATH);
        fs::write(
            &path,
            format!("{}# user edit\n", fs::read_to_string(&path).unwrap()),
        )
        .unwrap();
        let mut newer = settings.clone();
        newer.compiler = "1.18.2".into();
        let error = sync(temp.path(), &newer, WorkflowMode::Update).unwrap_err();
        assert!(error.to_string().contains("modified"));
        assert!(fs::read_to_string(path).unwrap().contains("# user edit"));
    }

