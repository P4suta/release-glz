    #[test]
    fn managed_workflow_modes_report_and_apply_only_verified_state() {
        let settings = test_settings();
        let temp = tempfile::tempdir().unwrap();

        let check = sync(temp.path(), &settings, WorkflowMode::Check).unwrap();
        assert!(check.changed);
        assert!(!check.written);
        assert!(check.diff.is_none());

        let diff = sync(temp.path(), &settings, WorkflowMode::Diff).unwrap();
        assert!(diff.changed);
        assert!(!diff.written);
        let diff = diff.diff.unwrap();
        assert!(diff.starts_with(&format!("--- {WORKFLOW_PATH}")));
        assert!(diff.contains("+# Generated by release-glz"));

        let created = sync(temp.path(), &settings, WorkflowMode::Update).unwrap();
        assert!(created.written);
        let unchanged = sync(temp.path(), &settings, WorkflowMode::Diff).unwrap();
        assert!(!unchanged.changed);
        assert!(unchanged.diff.is_none());

        let mut updated = settings.clone();
        updated.compiler = "1.18.2".into();
        let outcome = sync(temp.path(), &updated, WorkflowMode::Update).unwrap();
        assert!(outcome.changed);
        assert!(outcome.written);
        assert!(
            fs::read_to_string(temp.path().join(WORKFLOW_PATH))
                .unwrap()
                .contains("gleam-version: \"1.18.2\"")
        );
    }

    #[test]
    fn managed_state_schema_path_and_digest_are_each_required_before_overwrite() {
        for case in ["missing", "malformed", "schema", "path", "digest"] {
            let temp = tempfile::tempdir().unwrap();
            let settings = test_settings();
            sync(temp.path(), &settings, WorkflowMode::Update).unwrap();
            let state_path = temp.path().join(WORKFLOW_STATE_PATH);
            match case {
                "missing" => fs::remove_file(&state_path).unwrap(),
                "malformed" => fs::write(&state_path, b"not json").unwrap(),
                "schema" | "path" | "digest" => {
                    let mut state: WorkflowStateFile =
                        serde_json::from_slice(&fs::read(&state_path).unwrap()).unwrap();
                    match case {
                        "schema" => state.schema = "workflow-state/v2".into(),
                        "path" => state.path = ".github/workflows/other.yml".into(),
                        "digest" => state.sha256 = "0".repeat(64),
                        _ => unreachable!(),
                    }
                    fs::write(&state_path, serde_json::to_vec(&state).unwrap()).unwrap();
                }
                _ => unreachable!(),
            }
            let mut changed = settings;
            changed.compiler = "1.18.2".into();
            assert!(
                sync(temp.path(), &changed, WorkflowMode::Update).is_err(),
                "accepted invalid workflow state {case}"
            );
        }
    }

