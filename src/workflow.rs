const WORKFLOW_STATE_PATH: &str = ".release-glz/workflow-state.json";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkflowSettings {
    pub default_branch: String,
    pub manifest_path: PathBuf,
    pub compiler: String,
    pub environment: String,
    pub registry_credential_env: String,
    pub release_branch_prefix: String,
    pub action_sha: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WorkflowMode {
    Check,
    Diff,
    Update,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct WorkflowOutcome {
    pub schema: String,
    pub path: String,
    pub changed: bool,
    pub written: bool,
    pub diff: Option<String>,
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct WorkflowStateFile {
    schema: String,
    path: String,
    sha256: String,
}

pub fn default_action_sha() -> &'static str {
    RELEASE_GLZ_ACTION_SHA
}

pub fn render(default_branch: &str, manifest_path: &Path) -> String {
    render_configured(
        default_branch,
        manifest_path,
        "1.9.0",
        "release",
        "HEXPM_API_KEY",
        "release-glz/",
        RELEASE_GLZ_ACTION_SHA,
    )
    .expect("built-in workflow settings are valid")
}

pub fn render_configured(
    default_branch: &str,
    manifest_path: &Path,
    compiler: &str,
    environment: &str,
    registry_credential_env: &str,
    release_branch_prefix: &str,
    action_sha: &str,
) -> Result<String> {
    validate_git_ref(default_branch, "workflow default branch")?;
    if default_branch.starts_with("refs/") {
        bail!("workflow default branch must be a branch name, not a full ref");
    }
    validate_relative_path(manifest_path, "workflow manifest path")?;
    validate_release_branch_prefix(release_branch_prefix)?;
    let manifest = manifest_path.to_string_lossy().replace('\\', "/");
    validate_scalar(default_branch, "default branch", true)?;
    validate_scalar(&manifest, "manifest path", true)?;
    validate_scalar(environment, "approval environment", false)?;
    validate_environment_name(registry_credential_env, "registry credential environment")?;
    validate_scalar(release_branch_prefix, "release branch prefix", true)?;
    compiler
        .parse::<semver::Version>()
        .context("workflow compiler must be an exact semantic version")?;
    if action_sha.len() != 40 || !action_sha.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        bail!("release-glz Action must be pinned to a full commit SHA");
    }
    Ok(format!(
        r#"# Generated by release-glz. Re-run `release-glz init` to refresh.
name: release-glz

on:
  push:
    branches: [{default_branch}]
  pull_request:
    branches: [{default_branch}]
    types: [opened, synchronize, reopened]
  workflow_dispatch:
    inputs:
      source-sha:
        description: Full commit SHA to release
        required: true
        type: string
      reason:
        description: Reason for the manual release
        required: true
        type: string
      candidate-digest:
        description: Candidate digest for explicit promotion
        required: false
        type: string

permissions: {{}}

concurrency:
  group: release-glz-${{{{ github.repository }}}}-{manifest}
  cancel-in-progress: false

jobs:
  plan:
    name: Observe release intent
    if: ${{{{ github.event_name != 'pull_request' }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 15
    permissions:
      contents: read
      pull-requests: read
    outputs:
      release-required: ${{{{ steps.plan.outputs.release-required }}}}
      version: ${{{{ steps.plan.outputs.version }}}}
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          fetch-depth: 0
          ref: ${{{{ inputs.source-sha || github.sha }}}}
          persist-credentials: false
      - uses: erlef/setup-beam@{SETUP_BEAM_SHA} # v1.24.1
        with:
          otp-version: "28.0"
          gleam-version: "{compiler}"
      - uses: P4suta/release-glz@{action_sha}
        id: plan
        with:
          command: plan
          manifest-path: "{manifest}"
        env:
          {registry_credential_env}: ${{{{ secrets.{registry_credential_env} }}}}

  candidate:
    name: Build sealed Candidate
    needs: plan
    if: ${{{{ always() && (github.event_name != 'pull_request' || (github.event.pull_request.head.repo.full_name == github.repository && startsWith(github.head_ref, '{release_branch_prefix}'))) && (github.event_name == 'pull_request' || (needs.plan.result == 'success' && (github.event_name == 'workflow_dispatch' || needs.plan.outputs.release-required == 'true'))) }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      contents: read
      pull-requests: read
    outputs:
      release-required: ${{{{ needs.plan.outputs.release-required || 'true' }}}}
      version: ${{{{ steps.rehearse.outputs.version }}}}
      intent-digest: ${{{{ steps.rehearse.outputs.intent-digest }}}}
      candidate-digest: ${{{{ steps.rehearse.outputs.candidate-digest }}}}
      artifact-id: ${{{{ steps.upload.outputs.artifact-id }}}}
      artifact-digest: ${{{{ steps.upload.outputs.artifact-digest }}}}
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          fetch-depth: 0
          ref: ${{{{ inputs.source-sha || github.event.pull_request.head.sha || github.sha }}}}
          persist-credentials: false
      - uses: erlef/setup-beam@{SETUP_BEAM_SHA} # v1.24.1
        with:
          otp-version: "28.0"
          gleam-version: "{compiler}"
      - uses: P4suta/release-glz@{action_sha}
        id: rehearse
        with:
          command: rehearse
          manifest-path: "{manifest}"
          source-ref: ${{{{ inputs.source-sha || github.event.pull_request.head.sha || github.sha }}}}
          candidate: .release-glz/candidate
      - uses: actions/upload-artifact@{UPLOAD_ARTIFACT_SHA} # v7.0.1
        if: ${{{{ steps.rehearse.outcome == 'success' }}}}
        id: upload
        with:
          name: release-glz-candidate-${{{{ github.run_id }}}}
          path: .release-glz/candidate
          if-no-files-found: error
          include-hidden-files: true
          retention-days: 1

  authorize:
    name: Bind or verify Release PR intent
    needs: candidate
    if: ${{{{ always() && needs.candidate.result == 'success' && needs.candidate.outputs.candidate-digest != '' && (github.event_name == 'push' || github.event_name == 'pull_request') }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 10
    permissions:
      actions: read
      contents: read
      pull-requests: write
    outputs:
      state: ${{{{ steps.authorize.outputs.state }}}}
      pr-url: ${{{{ steps.authorize.outputs.pr-url }}}}
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          fetch-depth: 0
          ref: ${{{{ github.event.pull_request.head.sha || github.sha }}}}
          persist-credentials: false
      - uses: actions/download-artifact@{DOWNLOAD_ARTIFACT_SHA} # v8.0.1
        with:
          artifact-ids: ${{{{ needs.candidate.outputs.artifact-id }}}}
          path: .release-glz/candidate
          merge-multiple: true
      - uses: P4suta/release-glz@{action_sha}
        id: authorize
        with:
          command: release-pr
          manifest-path: "{manifest}"
          candidate: .release-glz/candidate
          dry-run: ${{{{ github.event_name == 'push' }}}}

  publish:
    name: Publish approved Candidate
    needs: [candidate, authorize]
    if: ${{{{ always() && needs.candidate.result == 'success' && needs.candidate.outputs.candidate-digest != '' && (github.event_name == 'workflow_dispatch' || (needs.authorize.result == 'success' && needs.authorize.outputs.state == 'awaiting_approval')) && (inputs.candidate-digest == '' || inputs.candidate-digest == needs.candidate.outputs.candidate-digest) }}}}
    runs-on: ubuntu-latest
    timeout-minutes: 30
    environment: {environment}
    permissions:
      actions: read
      contents: write
      id-token: write
      pull-requests: read
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          fetch-depth: 0
          ref: ${{{{ inputs.source-sha || github.sha }}}}
          persist-credentials: false
      - uses: actions/download-artifact@{DOWNLOAD_ARTIFACT_SHA} # v8.0.1
        with:
          artifact-ids: ${{{{ needs.candidate.outputs.artifact-id }}}}
          path: .release-glz/candidate
          merge-multiple: true
      - uses: P4suta/release-glz@{action_sha}
        id: verify
        with:
          command: verify
          manifest-path: "{manifest}"
          candidate: .release-glz/candidate
          online: "true"
      - uses: P4suta/release-glz@{action_sha}
        id: release
        with:
          command: release
          manifest-path: "{manifest}"
          candidate: .release-glz/candidate
        env:
          {registry_credential_env}: ${{{{ secrets.{registry_credential_env} }}}}
          RELEASE_GLZ_APPROVED_INTENT_DIGEST: ${{{{ needs.candidate.outputs.intent-digest }}}}
          RELEASE_GLZ_APPROVED_CANDIDATE_DIGEST: ${{{{ needs.candidate.outputs.candidate-digest }}}}
          RELEASE_GLZ_ACTIONS_ARTIFACT_ID: ${{{{ needs.candidate.outputs.artifact-id }}}}
          RELEASE_GLZ_ACTIONS_ARTIFACT_DIGEST: ${{{{ needs.candidate.outputs.artifact-digest }}}}
          RELEASE_GLZ_ENVIRONMENT: {environment}
          RELEASE_GLZ_MANUAL_SOURCE_SHA: ${{{{ inputs.source-sha }}}}
          RELEASE_GLZ_MANUAL_REASON: ${{{{ inputs.reason }}}}

  release-pr:
    name: Update rolling Release PR
    runs-on: ubuntu-latest
    if: ${{{{ github.event_name == 'push' }}}}
    timeout-minutes: 15
    permissions:
      contents: write
      pull-requests: write
    steps:
      - uses: actions/checkout@{CHECKOUT_SHA} # v7.0.1
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: erlef/setup-beam@{SETUP_BEAM_SHA} # v1.24.1
        with:
          otp-version: "28.0"
          gleam-version: "{compiler}"
      - uses: P4suta/release-glz@{action_sha}
        with:
          command: release-pr
          manifest-path: "{manifest}"
        env:
          {registry_credential_env}: ${{{{ secrets.{registry_credential_env} }}}}
"#
    ))
}

fn validate_environment_name(value: &str, field: &str) -> Result<()> {
    let valid = !value.is_empty()
        && value.bytes().enumerate().all(|(index, byte)| match byte {
            b'A'..=b'Z' | b'_' => true,
            b'0'..=b'9' => index > 0,
            _ => false,
        });
    if !valid {
        bail!("{field} must be an uppercase environment variable name");
    }
    Ok(())
}

fn validate_scalar(value: &str, field: &str, slash_allowed: bool) -> Result<()> {
    if value.is_empty()
        || value.bytes().any(|byte| {
            !(byte.is_ascii_alphanumeric()
                || matches!(byte, b'-' | b'_' | b'.')
                || (slash_allowed && byte == b'/'))
        })
    {
        bail!("{field} contains characters that are unsafe in generated workflow YAML");
    }
    Ok(())
}

pub fn init(
    repo_root: &Path,
    manifest_path: &Path,
    default_branch: &str,
    dry_run: bool,
) -> Result<PathBuf> {
    let path = repo_root.join(WORKFLOW_PATH);
    if path.exists() {
        bail!(
            "`{}` already exists; release-glz will not overwrite it",
            path.display()
        );
    }
    if !dry_run {
        fs::create_dir_all(path.parent().expect("workflow parent"))?;
        fs::write(&path, render(default_branch, manifest_path))
            .with_context(|| format!("failed to write `{}`", path.display()))?;
    }
    Ok(path)
}

pub fn sync(
    repo_root: &Path,
    settings: &WorkflowSettings,
    mode: WorkflowMode,
) -> Result<WorkflowOutcome> {
    let path = repo_root.join(WORKFLOW_PATH);
    let rendered = render_configured(
        &settings.default_branch,
        &settings.manifest_path,
        &settings.compiler,
        &settings.environment,
        &settings.registry_credential_env,
        &settings.release_branch_prefix,
        &settings.action_sha,
    )?;
    let current = fs::read_to_string(&path).ok();
    let changed = current.as_deref() != Some(rendered.as_str());
    let diff = (mode == WorkflowMode::Diff && changed)
        .then(|| workflow_diff(current.as_deref().unwrap_or(""), &rendered));
    let mut written = false;

    if mode == WorkflowMode::Update && changed {
        if let Some(current) = &current {
            let state_path = repo_root.join(WORKFLOW_STATE_PATH);
            let state: WorkflowStateFile = fs::read(&state_path)
                .ok()
                .and_then(|bytes| serde_json::from_slice(&bytes).ok())
                .with_context(|| {
                    format!(
                        "`{}` exists without a valid managed-state record; refusing to overwrite a modified workflow",
                        path.display()
                    )
                })?;
            if state.schema != "workflow-state/v1"
                || state.path != WORKFLOW_PATH
                || state.sha256 != digest(current.as_bytes())
            {
                bail!(
                    "`{}` was modified after generation; refusing to overwrite it",
                    path.display()
                );
            }
        }
        atomic_write(&path, rendered.as_bytes())?;
        let state = WorkflowStateFile {
            schema: "workflow-state/v1".into(),
            path: WORKFLOW_PATH.into(),
            sha256: digest(rendered.as_bytes()),
        };
        atomic_write(
            &repo_root.join(WORKFLOW_STATE_PATH),
            &serde_json::to_vec(&state)?,
        )?;
        written = true;
    }

    Ok(WorkflowOutcome {
        schema: "workflow/v1".into(),
        path: WORKFLOW_PATH.into(),
        changed,
        written,
        diff,
    })
}

fn atomic_write(path: &Path, contents: &[u8]) -> Result<()> {
    let parent = path.parent().context("managed file has no parent")?;
    fs::create_dir_all(parent)?;
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary.write_all(contents)?;
    temporary.as_file().sync_all()?;
    temporary
        .persist(path)
        .map_err(|error| error.error)
        .with_context(|| format!("failed to atomically write `{}`", path.display()))?;
    Ok(())
}

fn digest(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

fn workflow_diff(current: &str, rendered: &str) -> String {
    let mut output = format!("--- {WORKFLOW_PATH}\n+++ {WORKFLOW_PATH} (generated)\n");
    for line in current.lines() {
        output.push_str(&format!("-{line}\n"));
    }
    for line in rendered.lines() {
        output.push_str(&format!("+{line}\n"));
    }
    output
}

