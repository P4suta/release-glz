pub const WORKFLOW_PATH: &str = ".github/workflows/release-glz.yml";

const CHECKOUT_SHA: &str = "3d3c42e5aac5ba805825da76410c181273ba90b1"; // v7.0.1
const SETUP_BEAM_SHA: &str = "54075bcc5e249e4758d363f27d099f55d843f124"; // v1.24.1
const UPLOAD_ARTIFACT_SHA: &str = "043fb46d1a93c77aae656e7c1c64a875d1fc6a0a"; // v7.0.1
